import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
const modulePath=process.env.PLAYWRIGHT_MODULE;
if(!modulePath)throw new Error("PLAYWRIGHT_MODULE must point to Playwright.");
const {chromium}=await import(modulePath);
const browser=await chromium.launch({headless:true,args:["--no-sandbox","--use-gl=angle","--use-angle=swiftshader"]});
try{
 const page=await browser.newPage({viewport:{width:1280,height:800},deviceScaleFactor:1});
 const errors=[];
 page.on("pageerror",e=>errors.push(e.message));
 page.on("console",m=>{if(m.type()==="error")errors.push(m.text())});
 page.on("requestfailed",request=>errors.push(`requestfailed ${request.url()}: ${request.failure()?.errorText||"unknown"}`));
 await page.route("**/games/semester-survival-runner-3d/index.html*",async route=>{
  const response=await route.fetch();
  let body=await response.text();
  body=body.replace("https://cdn.jsdelivr.net/npm/three@0.180.0/build/three.module.js","/games/semester-survival-runner-3d/.ci-test/node_modules/three/build/three.module.js");
  body=body.replace("https://cdn.jsdelivr.net/npm/three@0.180.0/examples/jsm/","/games/semester-survival-runner-3d/.ci-test/node_modules/three/examples/jsm/");
  await route.fulfill({response,body});
 });
 await page.goto("http://127.0.0.1:4174/games/semester-survival-runner-3d/index.html?smoke=1",{waitUntil:"networkidle",timeout:60000});
 const mount=page.locator("#three-world");
 try{await page.waitForFunction(()=>document.querySelector("#three-world")?.dataset.rendererReady==="true",{timeout:60000});}catch(error){throw new Error(`${error.message}; browser errors: ${errors.join(" | ")||"none"}`)}
 const initial=await mount.evaluate(el=>({...el.dataset,canvasCount:el.querySelectorAll("canvas").length,canvasWidth:el.querySelector("canvas")?.width,canvasHeight:el.querySelector("canvas")?.height}));
 assert.ok(initial.canvasCount>0,"Three.js renderer did not create a canvas.");
 assert.ok(Number(initial.jayClipCount)>=5,"Unified Jay gameplay clips were not loaded.");
 assert.equal(initial.jayRunMotionFound,"true","The loader did not detect the authored in-place run clip.");
 assert.equal(initial.jayRunMotionFallback,"false","The gameplay loader unexpectedly used the legacy run-motion fallback.");
 await page.screenshot({path:"/tmp/jay-live-runner-home.png",fullPage:false});
 await page.locator("#play").click();
 await page.waitForFunction(()=>document.querySelector("#three-world")?.dataset.activeAnimation==="run",{timeout:10000});
 assert.equal(await page.evaluate(()=>window.__runnerSmoke.holdSafeRun()),true,"The browser test should isolate animation and event checks from random traffic collisions.");
 await page.waitForTimeout(900);
 const running=await mount.evaluate(el=>({...el.dataset}));
 assert.equal(running.activeAnimation,"run");
 assert.equal(running.jayRunPhase,"loop","The game should use the authored in-place loop from the first gameplay frame.");
 await page.keyboard.press("ArrowRight");
 await page.waitForTimeout(180);
 const lane=await mount.getAttribute("data-jay-lean");
 assert.notEqual(lane,null,"Lane lean telemetry should be available.");
 await page.keyboard.press("ArrowUp");
 await page.waitForFunction(()=>document.querySelector("#three-world")?.dataset.activeAnimation==="jump",{timeout:5000});
 await page.waitForFunction(()=>document.querySelector("#three-world")?.dataset.activeAnimation==="run",{timeout:5000});
 await page.keyboard.press("ArrowDown");
 await page.waitForFunction(()=>document.querySelector("#three-world")?.dataset.activeAnimation==="slide",{timeout:5000}).catch(async error=>{const state=await mount.evaluate(el=>({...el.dataset}));throw new Error("Slide input did not activate. Live renderer telemetry: "+JSON.stringify(state)+"; browser errors: "+errors.join(" | ")+"; original: "+error.message)});
 await page.waitForFunction(()=>document.querySelector("#three-world")?.dataset.activeAnimation==="run",{timeout:5000});
 await page.waitForTimeout(250);
 const ramp=await page.evaluate(()=>window.__runnerSmoke.probeRampVehicle());
 assert.ok(ramp,"Ramp vehicle browser probe should run.");
 assert.equal(ramp.boarding.phase,"climbing","Jay should board the incoming ramp vehicle.");
 assert.equal(ramp.boarding.rampCount,1,"The ramp vehicle must render as a real pooled 3D object.");
 assert.ok(ramp.boarding.surfaceHeight>0.5,"Jay should be raised onto the traversable ramp surface.");
 assert.equal(ramp.boarding.feetAligned,true,"Jay's feet must follow the ramp surface.");
 assert.ok(ramp.climbing.surfaceHeight>=1.1,"Jay should reach the elevated deck.");
 assert.equal(ramp.jumpOff.phase,"jumpingOff","Jump input should initiate a visible ramp dismount.");
 assert.equal(ramp.jumpOff.animation,"jump","The existing jump clip should be reused for the dismount.");
 assert.equal(ramp.jumpOff.feetAligned,true,"Jay's vertical trajectory should remain continuous during dismount.");
 assert.equal(ramp.exited.phase,"inactive","The ramp state should clear after landing.");
 assert.equal(ramp.exited.rampActive,false,"The ramp vehicle should resume normal movement after Jay exits.");
 assert.equal(ramp.recycled.rampCount,0,"The ramp vehicle should recycle only after passing behind the camera.");
 const trafficDensity=await page.evaluate(()=>window.__runnerSmoke.probeTrafficDensity());
 assert.equal(trafficDensity.beginner.count,6);
 assert.equal(trafficDensity.expert.count,8);
 assert.equal(trafficDensity.master.count,8);
 assert.ok(trafficDensity.master.spacing<trafficDensity.expert.spacing&&trafficDensity.expert.spacing<trafficDensity.beginner.spacing);
 const carry=await page.evaluate(()=>window.__runnerSmoke.probeCarryVehicle());
 assert.ok(carry,"Carry vehicle browser probe should run.");
 assert.equal(carry.approach.phase,"approaching");
 assert.equal(carry.approach.visible,true,"The forward-moving flatbed must appear ahead of Jay.");
 assert.equal(carry.boarding.phase,"boarding","Jay should enter the visible boarding transition.");
 assert.ok(carry.boarding.height>0,"Jay should visibly jump onto the rear platform.");
 assert.equal(carry.riding.phase,"riding");
 assert.equal(carry.riding.visible,true);
 assert.ok(carry.riding.height>=1,"Jay should remain at the platform height while riding.");
 assert.equal(carry.riding.lane,carry.riding.vehicleLane,"Jay and the carrying vehicle must share a lane.");
 assert.ok(carry.rideDistance>0,"Distance should continue accumulating during the ride.");
 assert.equal(carry.afterRide.phase,"slowing_down","The carry event should begin its timed deceleration.");
 assert.ok(carry.slowing.speed>0&&carry.slowing.speed<carry.baseSpeed,"The vehicle should decelerate smoothly.");
 assert.equal(carry.stopped.phase,"stopped");
 assert.equal(carry.stopped.speed,0,"The simulation should stop with the vehicle.");
 assert.equal(carry.trafficContinues,true,"Incoming traffic should continue moving while the carry vehicle is stopped.");
 assert.equal(carry.dismounting.phase,"dismounting");
 assert.ok(carry.dismounting.height>0,"Jay should visibly jump down from the platform.");
 assert.equal(carry.completed.phase,"completed");
 assert.equal(carry.completed.visible,true,"The vehicle must remain visible until Jay has exited.");
 assert.equal(carry.controlsRestored,true,"Normal lane controls should return after dismounting.");
 assert.equal(carry.recycled.phase,"inactive");
 assert.equal(carry.recycled.visible,false,"The vehicle should recycle only after leaving the camera.");
 const carryRestarts=await page.evaluate(()=>window.__runnerSmoke.probeCarryRestart());
 assert.equal(carryRestarts.length,7);
 assert.ok(carryRestarts.every(result=>result.wasVisible&&result.reset&&result.hidden),"Restart must clear and hide the carry vehicle from every event state.");
 await page.waitForFunction(()=>document.querySelector("#three-world")?.dataset.activeAnimation==="slide",{timeout:5000}).catch(async error=>{const state=await page.evaluate(()=>window.__runnerSmoke.state());throw new Error("Original player animation did not recover after carry/restart probes: "+JSON.stringify(state)+"; "+error.message)});
 const final=await mount.evaluate(el=>({...el.dataset}));
 assert.equal(final.rendererReady,"true");
 assert.equal(final.activeAnimation,"slide");
 assert.ok(Number(final.activeVehicleObstacles)>=0);
 assert.deepEqual(errors,[],"Browser console/runtime errors: "+errors.join(" | "));
 await page.screenshot({path:"/tmp/jay-live-runner-gameplay.png",fullPage:false});
 await mkdir("/tmp/jay-live-runner-results",{recursive:true});
 console.log("JAY_LIVE_RUNNER_E2E",JSON.stringify({initial,running,ramp,trafficDensity,carry,carryRestarts,final,errors},null,2));
}finally{await browser.close();}
